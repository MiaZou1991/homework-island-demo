const assert=require('node:assert/strict');
const {chromium}=require(process.env.PLAYWRIGHT_MODULE||'playwright');
const base='http://127.0.0.1:8189/';
(async()=>{
const browser=await chromium.launch({headless:true,channel:'chrome'});
try{
for(const width of [320,375,390,430]){
const page=await browser.newPage({viewport:{width,height:800},deviceScaleFactor:width===390?3:2,isMobile:true,hasTouch:true});
const errors=[];page.on('pageerror',e=>errors.push(e.message));
await page.goto(base+'family-tree.html?preview=1');
await page.locator('#previewNotice').waitFor({state:'visible'});
assert.equal(await page.locator('[data-moment]').count(),2,width+' seed moments');
assert.equal(await page.locator('[data-note]').count(),1,width+' seed note');
await page.locator('[data-open="moment"]').click();
await page.locator('#editorText').fill('新学会骑自行车');
await page.locator('#editorForm [name="category"]').selectOption('growth');
await page.locator('#saveEditor').click();
await page.locator('text=新学会骑自行车').waitFor();
assert.equal(await page.locator('[data-moment]').count(),3,width+' create moment');
await page.locator('[data-section="notes"]').click();
await page.locator('[data-note]').first().locator('input[name="reply"]').fill('今天超棒！');
await page.locator('[data-note]').first().locator('button[type="submit"]').click();
await page.locator('text=今天超棒！').waitFor();
await page.locator('[data-open="note"]').click();
await page.locator('#editorText').fill('今晚一起看星星');
await page.locator('#saveEditor').click();
await page.locator('text=今晚一起看星星').waitFor();
assert.equal(await page.locator('[data-note]').count(),2);
await page.locator('[data-section="hearts"]').click();
await page.locator('#heartTo').selectOption('mom');
await page.locator('#heartText').fill('谢谢妈妈陪我');
await page.locator('#heartForm button[type="submit"]').click();
await page.locator('[data-heart-view="sent"][aria-pressed="true"]').waitFor();
assert.equal(await page.locator('[data-heart]').count(),1,width+' sent heart');
await page.locator('#activeMember').selectOption('dad');
assert.equal(await page.locator('[data-heart]').count(),0,width+' dad cannot see kid-mom heart');
await page.locator('#activeMember').selectOption('mom');
await page.locator('[data-heart]').first().waitFor();
assert.equal(await page.locator('[data-heart]').count(),1,width+' mom sees heart');
await page.locator('[data-read]').first().click();
await page.locator('text=已收到这份心意 ♡').waitFor();
const overflow=await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth+1);
assert.equal(overflow,false,width+' no horizontal overflow');
assert.deepEqual(errors,[],width+' browser console errors');
await page.screenshot({path:'/tmp/family-tree-'+width+'.png',fullPage:true});
await page.reload();
await page.locator('#activeMember').selectOption('kid');
await page.locator('[data-section="moments"]').click();
assert.equal(await page.locator('[data-moment]').count(),3,width+' persisted moments after reload');
await page.close();
console.log('PASS family tree visual interactions',width);
}
const page=await browser.newPage({viewport:{width:390,height:800}});
await page.goto(base+'our-island.html?preview=1');
await page.locator('#loading').waitFor({state:'hidden',timeout:30000});
await page.locator('#mapToggle').click();
await page.locator('button[data-go="tree"]').click();
await page.locator('#visit').click();
assert.equal(await page.locator('#detail').evaluate(x=>x.open),true);
await page.locator('#treeEnter').click();
assert.equal(await page.locator('#treeExperience').evaluate(x=>x.open),true,'tree portal opens');
await page.frameLocator('#treeFrame').locator('#momentsTitle').waitFor();
await page.frameLocator('#treeFrame').locator('#backIsland').click();
assert.equal(await page.locator('#treeExperience').evaluate(x=>x.open),false,'tree portal closes back to island');
assert.equal(await page.evaluate(()=>IslandWalk.state.near),'tree','keeps tree location');
await page.close();
console.log('PASS island tree portal opens and closes with position preserved');
}finally{await browser.close();}
})().catch(err=>{console.error(err);process.exit(1);});
