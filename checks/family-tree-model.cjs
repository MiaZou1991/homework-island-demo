const assert=require('node:assert/strict');
const M=require('../dist/family-tree-model.js');
const time='2026-11-09T12:00:00.000Z';
let pub=M.publicState(null);
pub=M.applyPublic(pub,'kid',{type:'addMoment',day:'2026-11-09',category:'growth',text:'我会游泳啦'},time,'g1');
assert.equal(pub.moments.length,1);
assert.equal(pub.moments[0].author,'kid');
assert.throws(()=>M.applyPublic(pub,'dad',{type:'editMoment',id:'g1',day:'2026-11-09',category:'growth',text:'冒用他人修改'}),/自己的/);
assert.throws(()=>M.applyPublic(pub,'kid',{type:'editMoment',id:'g1',day:'2026-02-30',category:'growth',text:'错日期'}),/无效/);
pub=M.applyPublic(pub,'kid',{type:'editMoment',id:'g1',day:'2026-11-08',category:'together',text:'全家一起玩'},time);
assert.equal(pub.moments[0].category,'together');
pub=M.applyPublic(pub,'mom',{type:'addReply',targetType:'moment',momentId:'g1',text:'我记得这个开心瞬间'},time,'r-growth');
assert.equal(pub.replies.find(r=>r.id==='r-growth').momentId,'g1','memory supports family replies');

pub=M.applyPublic(pub,'mom',{type:'addNote',text:'一起去公园'},time,'n1');
pub=M.applyPublic(pub,'dad',{type:'addReply',noteId:'n1',text:'周六一起去'},time,'r1');
assert.equal(pub.replies.find(x=>x.id==='r1').author,'dad');
assert.throws(()=>M.applyPublic(pub,'kid',{type:'deleteNote',id:'n1'}),/自己的/);
assert.throws(()=>M.applyPublic(pub,'mom',{type:'editReply',id:'r1',text:'不可以'}),/自己的/);
pub=M.applyPublic(pub,'mom',{type:'deleteNote',id:'n1'});
assert.equal(pub.notes.length,0);
assert.equal(pub.replies.filter(x=>x.noteId==='n1').length,0,'deleting note removes its replies');
assert.equal(pub.replies.filter(x=>x.momentId==='g1').length,1,'unrelated memory reply is retained');
assert.throws(()=>M.applyPublic(pub,'kid',{type:'addMoment',day:'2026-11-09',category:'growth',text:' '.repeat(3)}),/1～300/);
assert.throws(()=>M.applyPublic(pub,'kid',{type:'addMoment',day:'2026-11-09',category:'growth',text:'x'.repeat(301)}),/1～300/);
assert.throws(()=>M.applyPublic(pub,'stranger',{type:'addNote',text:'wrong'}),/身份/);
let priv=M.privateState(null);
priv=M.applyPrivate(priv,'kid',{type:'sendHeart',to:'mom',text:'谢谢妈妈'},time,'h1');
priv=M.applyPrivate(priv,'dad',{type:'sendHeart',to:'kid',text:'爸爸爱你'},time,'h2');
assert.equal(M.visibleHearts(priv,'kid').length,2);
assert.deepEqual(M.visibleHearts(priv,'mom').map(x=>x.id),['h1']);
assert.deepEqual(M.visibleHearts(priv,'dad').map(x=>x.id),['h2']);
assert.deepEqual(M.visibleHearts(priv,'stranger'),[]);
assert.throws(()=>M.applyPrivate(priv,'dad',{type:'readHeart',id:'h1'}),/只有收信人/);
assert.throws(()=>M.applyPrivate(priv,'kid',{type:'sendHeart',to:'kid',text:'给自己'}),/送达/);
priv=M.applyPrivate(priv,'mom',{type:'readHeart',id:'h1'},time);
assert.equal(priv.hearts[0].readAt,time);
// Stage depends on elapsed months, NEVER heart count.
const when=(today,count=0)=>M.treeGrowth(count,{activationDate:'2021-11-10',today});
assert.deepEqual(when('2021-11-10').levels,[0,6,18,30,42,60]);
assert.deepEqual(['2021-11-10','2022-05-10','2023-05-10','2024-05-10','2025-05-10','2026-11-10'].map(d=>when(d).stage),[0,1,2,3,4,5]);
assert.equal(when('2026-11-09',10000).stage,4,'lots of hearts cannot accelerate five years');
assert.equal(when('2026-11-10',0).stage,5,'fifth anniversary grows without hearts');
assert.equal(when('2023-01-10',1000).decorationCount,3,'decoration display capped by age');
assert.equal(M.addMonths('2024-02-29',12),'2025-02-28','leap-day anniversary clamps to Feb 28');
assert.equal(M.dateInZone('2026-11-09T16:30:00.000Z','Asia/Shanghai'),'2026-11-10');
assert.equal(M.dateInZone('2026-11-09T16:30:00.000Z','America/Los_Angeles'),'2026-11-09');
priv=M.applyPrivate(priv,'mom',{type:'sendHeart',to:'dad',text:'谢谢你'},time,'h3');
assert.equal(M.dailyUsage(priv,'mom','2026-11-09'),1);
priv=M.applyPrivate(priv,'mom',{type:'reactRecord',recordType:'moment',recordId:'g1',targetAuthor:'kid'},time,'h4');
assert.equal(M.dailyUsage(priv,'mom','2026-11-09'),2);
assert.throws(()=>M.applyPrivate(priv,'mom',{type:'sendHeart',to:'kid',text:'再送一颗'},time,'h5'),/已送完/);
assert.throws(()=>M.applyPrivate(priv,'mom',{type:'reactRecord',recordType:'moment',recordId:'g1',targetAuthor:'kid'},'2026-11-10T12:00:00.000Z','h6'),/已经送过/);
assert.equal(M.applyPrivate(priv,'mom',{type:'sendHeart',to:'dad',text:'谢谢你'},time,'h3').hearts.length,3,'idempotency prevents duplicate debit');
priv=M.applyPrivate(priv,'mom',{type:'sendHeart',to:'kid',text:'明天送心'},'2026-11-10T12:00:00.000Z','h7');
assert.equal(M.dailyUsage(priv,'mom','2026-11-10'),1,'tomorrow quota resets');
assert.throws(()=>M.applyPrivate(priv,'mom',{type:'reactRecord',recordType:'note',recordId:'n1',targetAuthor:'mom'},'2026-11-10T12:00:00.000Z','h8'),/自己的/);

pub=M.applyPublic(pub,'kid',{type:'deleteMoment',id:'g1'});
assert.equal(pub.replies.some(r=>r.id==='r-growth'),false,'deleting a memory removes its replies');
assert.equal(pub.hasOwnProperty('hearts'),false,'public records contain no private hearts');
assert.equal(priv.hasOwnProperty('notes'),false,'private store contains no shared notes');
console.log('PASS family tree model: moments, notes, reply ownership, dates, private hearts');
